const SUPPORTED = ["en", "de", "pl"];
const DEFAULT_LANG = "en";
const STORAGE_KEY = "harbor9-lang";

// Resolve a BCP-47 tag (e.g. "de-AT") down to one of our supported languages.
function normalize(tag) {
  if (!tag) return null;
  const base = tag.toLowerCase().split("-")[0];
  return SUPPORTED.includes(base) ? base : null;
}

// Priority: explicit user choice (localStorage) > browser languages > default.
function detectLanguage() {
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (normalize(saved)) return saved;
  } catch (e) {
    /* localStorage may be unavailable (private mode) — fall through */
  }

  const candidates =
    navigator.languages && navigator.languages.length
      ? navigator.languages
      : [navigator.language];

  for (const tag of candidates) {
    const lang = normalize(tag);
    if (lang) return lang;
  }
  return DEFAULT_LANG;
}

// Look up a key for the active language, with a template for {current}/{total}.
function t(key, vars) {
  const dict = translations[currentLang] || translations[DEFAULT_LANG];
  let str = dict[key];
  if (str === undefined) str = translations[DEFAULT_LANG][key] || key;
  if (vars) {
    str = str.replace(/\{(\w+)\}/g, (_, name) =>
      vars[name] !== undefined ? vars[name] : `{${name}}`
    );
  }
  return str;
}

let currentLang = DEFAULT_LANG;

// Apply the active language to the whole document.
function applyLanguage(lang) {
  currentLang = normalize(lang) || DEFAULT_LANG;
  document.documentElement.lang = currentLang;

  // Text content
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    el.textContent = t(el.getAttribute("data-i18n"));
  });

  // Input / textarea placeholders
  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    el.setAttribute("placeholder", t(el.getAttribute("data-i18n-placeholder")));
  });

  // Accessible labels / iframe titles
  document.querySelectorAll("[data-i18n-title]").forEach((el) => {
    el.setAttribute("title", t(el.getAttribute("data-i18n-title")));
  });
  document.querySelectorAll("[data-i18n-aria-label]").forEach((el) => {
    el.setAttribute("aria-label", t(el.getAttribute("data-i18n-aria-label")));
  });

  // Let the web components (<harbor-lang-switch>, <harbor-gallery>) react
  document.dispatchEvent(
    new CustomEvent("languagechange", { detail: { lang: currentLang } })
  );
}

function setLanguage(lang) {
  const norm = normalize(lang);
  if (!norm) return;
  try {
    localStorage.setItem(STORAGE_KEY, norm);
  } catch (e) {
    /* ignore storage failures */
  }
  applyLanguage(norm);
}

// Expose the translate helper for other scripts (gallery caption).
window.i18n = { t, setLanguage, get lang() { return currentLang; } };

document.addEventListener("DOMContentLoaded", () => {
  applyLanguage(detectLanguage());
});
